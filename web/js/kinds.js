/** Вид, приведённый к одному написанию: по нему и ищем. */
export function kindKey(kind) {
  return String(kind || '').toLowerCase().replace(/[\s-]/g, '').replace(/ё/g, 'е');
}

/** Что известно о виде: силуэт, семейство цвета и название группы. */
export function kindInfo(kind) {
  const found = KINDS.get(kindKey(kind));
  if (found) return { shape: found[0], family: found[1], group: found[2] };
  // Незнакомый вид — не повод оставить объект без значка: он выглядел бы
  // в дереве иначе, чем соседи. Группой становится сам вид, как его назвали.
  return { shape: 'unknown', family: 'other', group: String(kind || 'Прочее') };
}

/**
 * Значок вида — готовый SVG.
 *
 * @param {string} kind вид объекта, как его называет платформа
 * @param {string} [title] всплывающая подсказка; по умолчанию сам вид
 */
export function kindIcon(kind, title = kind) {
  const { shape, family } = kindInfo(kind);
  const hint = String(title || '').replace(/"/g, '&quot;');
  return `<svg class="ob-icon ob-icon--${family}" ${BOX} role="img" aria-hidden="true"`
    + `><title>${hint}</title>${SHAPES[shape] || SHAPES.unknown}</svg>`;
}

/** Название группы верхнего уровня: «Документы», «Регистры сведений». */
export function kindGroup(kind) {
  return kindInfo(kind).group;
}
