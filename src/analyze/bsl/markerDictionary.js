/**
 * Словарь маркеров в комментариях кода 1С.
 *
 * Зачем отдельный файл. Изменённый типовой модуль на несколько тысяч строк —
 * это почти целиком код вендора, в который интегратор вставил десяток строк.
 * Найти эти строки можно только по комментариям-пометкам. Но пометками
 * пользуется не только интегратор: сам вендор и сама платформа расставляют
 * в типовом коде комментарии ровно того же вида.
 *
 * Реальный случай, ради которого словарь и появился: в 1С:ERP типовой код
 * обрамлён комментариями «//++ НЕ УТ», «//++ НЕ УТКА», «// Локализация».
 * Это не фамилии и не префиксы — это условная сборка: ERP, КА и УТ собираются
 * из общих исходников, и такими метками отмечены куски, не попадающие
 * в младшие конфигурации. Приняв их за авторские вставки, аудит записал
 * «НЕ УТКА» и «НЕ УТ» в разработчики и выдал сотню замечаний к коду вендора.
 *
 * Поэтому здесь два перечня:
 *
 *   VENDOR_MARKERS  — пометки вендора и платформы. Кодом интегратора НЕ являются
 *                     ни при каких условиях, участок пропускается целиком.
 *   AUTHOR_SIGNALS  — признаки, по которым комментарий опознаётся как пометка
 *                     разработчика: фамилия, префикс проекта, подчёркивание
 *                     в имени, номер задачи, дата.
 *
 * Оба перечня пополняемые: при встрече новой конфигурации сюда дописывается
 * строка, а не правится логика поиска.
 */

import { WORD_CHAR, B, E } from './wordBoundary.js';

/** Чем подписывается замечание, для которого автора установить не удалось. */
export const UNKNOWN_AUTHOR = 'автор не определён';

/**
 * Парные маркеры: открывающий и соответствующий закрывающий.
 *
 * `wordy` — маркер словесный («// Начало изменений»), для него дополнительно
 * требуется слово о правке (EDIT_WORDS), иначе вставкой станет любой
 * структурный комментарий вида «// Начало цикла».
 */
export const PAIRED_MARKERS = [
  // //++ Иванов … //-- Иванов   (самый распространённый вариант)
  // `(?!>)` защищает от «//-->» в HTML-подобных комментариях.
  { open: /^\s*\/\/\s*\+\+/, close: /^\s*\/\/\s*--(?!>)/, wordy: false },
  // //{{ Иванов … //}} Иванов
  { open: /^\s*\/\/\s*\{\{/, close: /^\s*\/\/\s*\}\}/, wordy: false },
  // //<<< Начало правки >>> … //>>> Конец правки <<<
  { open: /^\s*\/\/\s*<<+/, close: /^\s*\/\/\s*>>+/, wordy: false },
  // //!! правка … //!!
  { open: /^\s*\/\/\s*!!+/, close: /^\s*\/\/\s*!!+/, wordy: false },
  //
  // Звёздочки (`//** …`) в этот перечень НЕ входят намеренно. Ими размечены
  // описания вложенных структур в комментариях БСП:
  //   //    * Издатель - ФиксированнаяСтруктура - информация об издателе:
  //   //        ** CN - commonName;
  // На реальной ERP такой маркер дал 900 ложных вставок и 38 тысяч «авторских»
  // строк в типовом коде — с авторами вида «CN - commonName;».
  {
    // Слово о правке должно стоять В НАЧАЛЕ комментария. Иначе «начало»
    // и «конец» ловятся в обычной прозе: «Блок запроса новостей. Начало»,
    // «время начала и окончания блокировки» — проверено на реальной ERP.
    //
    // И это должно быть отдельное слово: без границы справа под правило
    // попадали имена обработчиков «//НачалоПериодаНачалоГодаПриИзменении»
    // («ПриИзменении» проходит по EDIT_WORDS).
    open: new RegExp(`^\\s*//[\\s\\-=*+_#]*(начал[оа]|added|begin)${E}`, 'i'),
    close: new RegExp(`^\\s*//[\\s\\-=*+_#]*(конец|окончание|end)${E}`, 'i'),
    wordy: true,
  },
];

/**
 * Слова, по которым словесный маркер признаётся пометкой о правке,
 * а не обычным структурным комментарием.
 */
export const EDIT_WORDS =
  /(изменени|доработ|вставк|правк|модификац|добавлен|коррект|адаптац|интеграц|расширен)/i;

/**
 * Пометки вендора и платформы. Код внутри них — типовой.
 *
 * Проверяется по телу комментария (без ведущих «//» и знаков маркера).
 */
/*
 * Правая граница слова. Через `\b` её задавать нельзя: в JavaScript `\b`
 * определена по [A-Za-z0-9_], кириллица туда не входит, и «СтандартныеПодсистемы.»
 * границей не заканчивается — задокументированные грабли проекта.
 */
export const VENDOR_MARKERS = [
  // --- Условная сборка типовых решений 1С -----------------------------------
  // ERP, КА и УТ собираются из общих исходников; такими метками отмечены
  // фрагменты, не попадающие в младшие конфигурации.
  //
  // Перечень кодов у вендора открытый: на реальной ERP нашлись НЕ УТ, НЕ УТКА,
  // НЕ ГОСИС (1 144 участка), НЕ УХ, НЕ ПУ21. Поэтому правило общее: «НЕ» плюс
  // короткий код заглавными — это условная сборка. Человек так не подписывается.
  /^НЕ\s+[A-ZА-ЯЁ0-9_.\-]{1,15}(\s|$|[,.;:_-])/,
  /^(НЕ\s+)?(УТ|УТКА|КА|ЕРП|ERP|УПП|БП|ЗУП|ЗКГУ|РОЗНИЦА|УНФ|КОРП|БАЗОВАЯ|ПРОФ|ГОСИС|УХ)(\s|$|[,.;:_-])/i,
  /^(НЕ\s+)?(ФРЕШ|FRESH|СЕРВИС|SAAS|ОБЛАКО)(\s|$|[,.;:_-])/i,
  // Блоки, помеченные вендором как устаревшие: «//++ Устарело_Производство21».
  /^УСТАРЕЛО[_\s]/i,
  // --- Локализация и национальные особенности --------------------------------
  /^(НЕ\s+)?(ЛОКАЛИЗАЦИЯ|ЛОКАЛИЗАЦИИ|НАЦ(ИОНАЛЬНЫЕ)?[\s_.]*ОСОБЕННОСТ)/i,
  /^(НЕ\s+)?(УКРАИНА|БЕЛАРУСЬ|БЕЛОРУССИЯ|КАЗАХСТАН|МОЛДОВА|АРМЕНИЯ|ГРУЗИЯ|ЛИТВА|ЛАТВИЯ|ЭСТОНИЯ)/i,
  // --- Библиотеки 1С ---------------------------------------------------------
  // БСП встраивается в типовые конфигурации именно такими комментариями:
  // «// Начало СтандартныеПодсистемы.БазоваяФункциональность».
  new RegExp(`^(НЕ\\s+)?(СтандартныеПодсистемы|БСП|БиблиотекаСтандартныхПодсистем)${E}`, 'i'),
  new RegExp(`^(НЕ\\s+)?(БиблиотекаЭлектронныхДокументов|БЭД|БиблиотекаИнтернетПоддержки|БИП)${E}`, 'i'),
  new RegExp(`^(НЕ\\s+)?(БиблиотекаПодключаемогоОборудования|БПО|БиблиотекаТехнологииСервиса|БТС)${E}`, 'i'),
  new RegExp(`^(НЕ\\s+)?(ОбменДаннымиXDTO|УправлениеДоступом|РаботаСФайлами|ЭлектронноеВзаимодействие)${E}`, 'i'),
  // --- Конструкторы и служебные вставки платформы ----------------------------
  /^_*(КОНСТРУКТОР|MRG|ОБРАБОТЧИК|ЭЛЕМЕНТ_ФОРМЫ|СИСТЕМА_КОМПОНОВКИ)/i,
  /^_*(CONSTRUCTOR|HANDLER)/i,
  // --- Служебные пометки самого вендора --------------------------------------
  new RegExp(`^(ТРЕБУЕТСЯ|УСТАРЕЛО|OBSOLETE|DEPRECATED|ПЕРЕОПРЕДЕЛЯЕМЫЙ)${E}`, 'i'),
  /^(ВНИМАНИЕ|ВАЖНО|NB)\s*[!:.]/i,
];

/**
 * Дополнительная защита: маркер платформы узнаётся по любому месту в строке,
 * а не только по началу тела. Конструктор запроса пишет его сразу за «//{{».
 */
export const PLATFORM_MARKER = /\{\{\s*_*(КОНСТРУКТОР|MRG|ОБРАБОТЧИК|ЭЛЕМЕНТ_ФОРМЫ)/i;

/** Дата в комментарии: 02.08.2019, 02-08-19, 2019/08/02. */
export const DATE_RE = /(\d{2}[.\-/]\d{2}[.\-/]\d{2,4})|(\d{4}[.\-/]\d{2}[.\-/]\d{2})/;

/** Номер задачи: #2745, №2745, JIRA-123, TASK_45. */
export const TICKET_RE = new RegExp(`([#№]\\s*\\d+)|(${B}[A-ZА-Я]{2,10}[-_]\\d{1,6}${E})`);

/** Фамилия с инициалами: «Иванов И.И.», «И.И. Иванов». */
export const SURNAME_INITIALS_RE = new RegExp(
  `([А-ЯЁ][а-яё]{2,}\\s+[А-ЯЁ]\\.\\s?[А-ЯЁ]?\\.?)|([А-ЯЁ]\\.\\s?[А-ЯЁ]?\\.?\\s*[А-ЯЁ][а-яё]{2,})`,
);

/** Только инициалы, отдельным словом: «А.П.», «А.П», «А.». */
export const INITIALS_ONLY_RE = /^[А-ЯЁA-Z]\.\s?[А-ЯЁA-Z]?\.?$/;

/**
 * Пометки-«напоминалки», которые ставит сам же разработчик, но именем автора
 * они не являются: «//++ 050920 FIXME».
 */
export const NOT_A_NAME = new Set([
  'FIXME', 'TODO', 'HACK', 'XXX', 'NB', 'OK', 'BUG', 'WTF', 'ВНИМАНИЕ', 'ВАЖНО', 'ПРАВКА',
]);

/**
 * Похож ли отдельный токен на имя, фамилию или тег доработки.
 *
 * Годятся: «Иванов», «Ким», «ДРБ», «ДРБ_1234», «инт_и_Иванов».
 * Не годятся: «180920», «комментарии», «дополнительно», «FIXME».
 */
export function looksLikeName(token) {
  const word = String(token || '').replace(/^[^0-9A-Za-zА-Яа-яЁё_]+|[^0-9A-Za-zА-Яа-яЁё_]+$/g, '');
  if (word.length < 2 || word.length > 40) return false;
  if (/^\d+$/.test(word)) return false;
  if (NOT_A_NAME.has(word.toUpperCase())) return false;
  // Составное имя через подчёркивание — принятая у интеграторов форма.
  if (word.includes('_')) return /[A-Za-zА-Яа-яЁё]/.test(word);
  // Иначе — слово с заглавной буквы: фамилия или аббревиатура проекта.
  return new RegExp(`^[А-ЯЁA-Z][${WORD_CHAR}-]+$`).test(word);
}

/** Одиночная фамилия: слово с заглавной, не аббревиатура. */
export const SURNAME_RE = /(^|\s)[А-ЯЁ][а-яё]{3,}(\s|$|[,;.])/;

/**
 * Составное имя через подчёркивание — принятая у интеграторов форма
 * «инт_и_Иванов», «ДРБ_Иванов», «abs_Petrov».
 */
export const UNDERSCORE_NAME_RE = new RegExp(`[${WORD_CHAR}]*_[${WORD_CHAR}]*[А-Яа-яЁёA-Za-z][${WORD_CHAR}]*`);

/** Знаки оформления по краям маркера. */
export const NOISE_EDGES = /^[\s/+\-{}<>*=#!№[\]()]+|[\s/+\-{}<>*=#!№[\]()]+$/g;

/**
 * Служебные слова, которые не являются именем автора.
 *
 * Границы слова заданы явными lookaround по кириллице: `\b` в JavaScript
 * определена через [A-Za-z0-9_], поэтому без левой границы предлог «в»
 * вырезался из середины фамилии — «Петров» превращался в «Петро».
 */
export const NOISE_WORDS = new RegExp(
  `(?<![${WORD_CHAR}])(начало|конец|начала|окончание|изменени[${WORD_CHAR}]*`
  + `|доработк[${WORD_CHAR}]*|вставк[${WORD_CHAR}]*|правк[${WORD_CHAR}]*`
  + `|модификаци[${WORD_CHAR}]*|добавлен[${WORD_CHAR}]*|блок[${WORD_CHAR}]*`
  + `|коррект[${WORD_CHAR}]*|код|кода|адаптац[${WORD_CHAR}]*`
  + `|задач[${WORD_CHAR}]*|версия|для|по|от|в|на|и)(?![${WORD_CHAR}])`,
  'gi',
);

/**
 * Пометка вендора или платформы?
 *
 * @param {string} body тело комментария без «//» и знаков маркера
 * @param {string} [rawComment] комментарий целиком — для маркеров платформы
 */
export function isVendorMarker(body, rawComment = '') {
  if (rawComment && PLATFORM_MARKER.test(rawComment)) return true;
  const text = String(body || '').trim();
  if (!text) return false;
  return VENDOR_MARKERS.some((re) => re.test(text));
}

/**
 * Похоже ли содержимое комментария на подпись разработчика.
 *
 * @param {string} body тело комментария
 * @param {RegExp|null} prefixRe известные префиксы доработок этой конфигурации
 */
export function hasAuthorSignal(body, prefixRe = null) {
  const text = String(body || '').trim();
  if (!text) return false;
  if (prefixRe) {
    prefixRe.lastIndex = 0;
    if (prefixRe.test(text)) {
      prefixRe.lastIndex = 0;
      return true;
    }
    prefixRe.lastIndex = 0;
  }
  return DATE_RE.test(text)
    || TICKET_RE.test(text)
    || SURNAME_INITIALS_RE.test(text)
    || SURNAME_RE.test(text);
}

/**
 * Регулярное выражение по известным префиксам доработок конфигурации.
 *
 * Продолжение имени берём классом с кириллицей, а не `\w`: иначе от
 * «инт_и_Иванов» остаётся «инт_», и все правки сливаются в одного автора.
 *
 * @param {string[]} prefixes
 * @returns {RegExp|null}
 */
export function buildPrefixRegex(prefixes) {
  const cleaned = [...new Set(
    (prefixes || []).map((p) => String(p || '').trim()).filter((p) => p.length >= 2),
  )];
  if (!cleaned.length) return null;
  const escaped = cleaned.map((p) => p.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'));
  return new RegExp(`(?:${escaped.join('|')})[${WORD_CHAR}]*`, 'gi');
}
