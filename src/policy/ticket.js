/**
 * Номер задачи: есть, не по формату или нет вовсе.
 *
 * Формат номера — проектный и живёт в регламенте: где-то это `#0001234`,
 * где-то `XIM-78`, а где-то просто число без всяких значков. Поэтому здесь
 * **нет** привязки ни к «#», ни к «№»: регламент задаёт маску, а программа
 * лишь применяет её.
 *
 * Различать «номера нет» и «номер не по формату» требовал пользователь
 * (20.08.2026): это разные ошибки разработчика и разные способы исправления.
 * Забыл номер — вспомни задачу; написал по-своему — приведи к формату проекта.
 * Признаком «что-то похожее на номер задачи всё же написано» служит любая
 * запись с цифрами: ключ задачи с буквенным префиксом (`XIM-78`), номер
 * со значком (`#3344`, `№ 12`) или отдельно стоящее число.
 */

/**
 * Похоже на ссылку на задачу: ключ с дефисом, номер со значком либо число.
 *
 * Со значком годится любое число: «#12» — это явно попытка указать задачу,
 * пусть и не по формату. Без значка число должно быть хотя бы трёхзначным,
 * иначе «правка 2 отчётов» превратилась бы в номер задачи.
 */
const TICKET_SHAPE = /(?:^|[\s(:;,])[#№]?\s*(?:[A-Za-zА-Яа-яЁё]{1,10}-\d{1,7}|\d{3,9})(?![\wА-Яа-яЁё])/;

/** Номер со значком: «#12» — попытка указать задачу, пусть и короткая. */
const MARKED_NUMBER = /[#№]\s*\d+/;

/** Служебные комментарии платформы: номер задачи в них не требуется. */
const SERVICE_COMMENTS = [
  'создание хранилища конфигурации',
  'создание хранилища',
  'помещение конфигурации в хранилище',
];

/**
 * @param {string} text комментарий помещения или тело пометки
 * @param {RegExp|null} mask маска номера задачи из регламента
 * @returns {'ok'|'malformed'|'none'}
 */
export function ticketPresence(text, mask) {
  const value = String(text || '').trim();
  if (!value) return 'none';
  if (mask && mask.test(value)) return 'ok';
  return (TICKET_SHAPE.test(value) || MARKED_NUMBER.test(value)) ? 'malformed' : 'none';
}

/**
 * Комментарий поставлен платформой, а не разработчиком.
 *
 * «Создание хранилища конфигурации» пишет сама 1С при создании хранилища:
 * задачи за этим помещением нет и быть не может, и требовать её номер —
 * заведомо ложное замечание (замечание пользователя, 20.08.2026).
 */
export function isServiceComment(text) {
  const value = String(text || '').trim().toLowerCase();
  if (!value) return false;
  return SERVICE_COMMENTS.some((known) => value === known || value.startsWith(`${known}.`));
}
